from __future__ import annotations

import torch
import torch.nn as nn

from CPN_utils import ComplexPair, Lambda


class ThetaDefs(nn.Module):
    """Parameter-free container describing an additive XY deformation."""

    name = "ThetaDef"

    def __init__(self, ndims=2) -> None:
        """Initialize the single deformation degree of freedom."""
        super().__init__()
        self.DOF = 1
        self.ndims = ndims

    def __repr__(self) -> str:
        """Return the short deformation name."""
        return self.name

    def complexify(
            self,
            thetas: torch.Tensor,
            deforms: torch.Tensor,
    ) -> torch.Tensor:
        """ Return complexified angles """
        assert thetas.shape[-self.ndims:] == deforms.shape, \
            "deformation field shape has to be the same as the lattice shape"
        return thetas + 1j*deforms


class FlowedDeformations(nn.Module):
    """Project learned vector fields onto the tangent space of a sphere."""

    name = "FlowDef"

    def __init__(self, N: int) -> None:
        """Initialize a flow for CP(N) represented with real coordinates."""
        super().__init__()
        self.N = N
        self.DOF = 2 * (N + 1)

    def __repr__(self) -> str:
        """Return the short deformation name."""
        return self.name

    def forward(
        self,
        x: torch.Tensor,
        field: torch.Tensor,
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """Project ``field`` tangentially and return it with its divergence."""
        projection = torch.sum(field * x, dim=-1, keepdim=True)
        tangent_field = field - projection * x
        divergence = -(self.DOF + 1) * projection.squeeze(-1)
        lattice_dims = tuple(range(1, divergence.ndim))
        return tangent_field, divergence.sum(dim=lattice_dims)


class HomogeneousDeformations(nn.Module):
    """Homogeneous CP(N) contour deformation and analytic Jacobian."""

    name = "HomogDef"

    def __init__(
        self,
        N: int,
        device: str | torch.device = "cpu",
    ) -> None:
        """Initialize the fixed complex-structure matrices."""
        super().__init__()
        self.N = N
        self.DOF = N + 1
        self.register_buffer("eye", torch.eye(2 * self.DOF, device=device))

        blocks = [torch.tensor([[0, -1], [1, 0]])] * (N + 1)
        omega = torch.block_diag(*blocks).to(torch.float32).to(device)
        self.register_buffer("omega", omega)

    def __repr__(self) -> str:
        """Return the short deformation name."""
        return self.name

    def deformx(self, x: torch.Tensor, alphas: torch.Tensor) -> torch.Tensor:
        """Return the imaginary displacement generated by ``alphas``."""
        if x.is_complex() or alphas.is_complex():
            raise ValueError(
                "HomogeneousDeformations expects real interleaved CP(N) "
                "coordinates and real deformation parameters"
            )
        if alphas.shape[-1] != self.DOF:
            raise ValueError("alphas have an incorrect final dimension")

        diagonal = torch.diag_embed(
            torch.repeat_interleave(alphas, repeats=2, dim=-1))
        for _ in range(x.ndim - alphas.ndim):
            diagonal = diagonal.unsqueeze(0)
        omega = self.omega.to(dtype=x.dtype, device=x.device)
        return torch.einsum("...ij,...j->...i", diagonal @ omega, x)

    def deform(self, x: torch.Tensor, alphas: torch.Tensor) -> ComplexPair:
        """Apply the contour deformation without materializing a complex tensor.

        The two tensors in the returned :class:`~CPN_utils.ComplexPair` are
        the real and imaginary parts of the holomorphically deformed
        interleaved coordinate field.  Keeping this representation is what
        lets the CP(N) pipeline run on MPS, which does not support complex
        dtypes.
        """
        y = self.deformx(x, alphas)
        return ComplexPair(x * Lambda(y).unsqueeze(-1), y)

    def complexify(self, x: torch.Tensor, alphas: torch.Tensor) -> ComplexPair:
        """Compatibility alias for :meth:`deform`.

        Despite the historical name, this deliberately returns a pair of
        real tensors.  Call ``.cpu().to_complex()`` only for output that
        truly requires a native complex tensor.
        """
        return self.deform(x, alphas)

    def detJac(self, x: torch.Tensor, alphas: torch.Tensor) -> torch.Tensor:
        """Return the real per-site determinant of the deformation Jacobian.

        For a real sampled field and real ``alphas``, the former complex
        matrix is a block-diagonal matrix plus a rank-one update.  Its
        determinant is real and can be evaluated entirely in real
        arithmetic.  This avoids constructing ``ComplexDouble`` solely for
        ``torch.linalg.det``, an operation unsupported by MPS.
        """
        y = self.deformx(x, alphas)
        normalization = Lambda(y)
        alpha_squared = alphas.square()
        component_norms = x.unflatten(-1, (self.DOF, 2)).square().sum(dim=-1)
        factors = normalization.square().unsqueeze(-1) - alpha_squared
        base_determinant = factors.prod(dim=-1)

        # Matrix-determinant lemma, expanded without division so the formula
        # remains finite when an individual ``lambda**2 - alpha_i**2`` is 0.
        other_products = []
        for component in range(self.DOF):
            remaining = torch.cat(
                (factors[..., :component], factors[..., component + 1 :]),
                dim=-1,
            )
            other_products.append(
                remaining.prod(dim=-1)
                if self.DOF > 1
                else torch.ones_like(base_determinant)
            )
        rank_one_update = (
            alpha_squared
            * component_norms
            * torch.stack(other_products, dim=-1)
        ).sum(dim=-1)
        return (base_determinant + rank_one_update) / normalization.square()
